#!/bin/sh
# container-agent.sh PROMPT_FILE NAME
# Run an editing agent in a container that sees only a fresh worktree's files, run CHECK_CMD in a
# second container, and commit on success. Worktrunk creates the worktree, so its pre-start hooks
# prepare it. Never pushes. No-op runs remove the worktree and branch; successful runs keep only
# the branch; failed runs keep the worktree for inspection.
set -eu
prompt_file=$1 name=$2
image=${AGENT_IMAGE:?set AGENT_IMAGE to an image with your agent and toolchain}
agent=${AGENT_CMD:?set AGENT_CMD to the agent command; it reads the prompt on stdin}
check=${CHECK_CMD:?set CHECK_CMD to the command that must pass before committing}
base=${BASE_REF:-main}

root=$(git rev-parse --show-toplevel)
prompt="$root/$prompt_file"
[ -f "$prompt" ] || { echo "missing prompt file $prompt_file" >&2; exit 1; }
branch="agent/$name-$(date +%Y%m%d-%H%M%S)"

tree=$(wt switch --create "$branch" --base "$base" --no-cd --format=json | jq -r .path)
echo "worktree $tree on $branch"

# Mount the working tree only. .git stays read-only: Git on the host follows it, and a gitdir or
# config the agent wrote there could run commands outside the container. --mount, unlike
# --volume, fails when Docker can't see the path instead of mounting an empty directory.
sandbox() {
  docker run --rm --interactive --init --cap-drop ALL --security-opt no-new-privileges \
    --user "$(id -u):$(id -g)" --tmpfs /tmp --tmpfs /home/agent --env HOME=/home/agent \
    --mount "type=bind,source=$tree,target=/work" \
    --mount "type=bind,source=$tree/.git,target=/work/.git,readonly" --workdir /work "$@"
}

# Only the variables named in AGENT_ENV reach the agent; the check never sees them.
set --
for var in ${AGENT_ENV:-}; do set -- "$@" --env "$var"; done
sandbox "$@" "$image" sh -c "$agent" < "$prompt"

cd "$tree"
if [ -z "$(git status --porcelain)" ]; then
  echo "agent made no changes; removing worktree and branch"
  cd "$root"
  wt remove "$branch" --no-hooks --foreground
  exit 0
fi

if ! sandbox "$image" sh -c "$check" < /dev/null; then
  echo "check failed; worktree kept for inspection: $tree" >&2
  exit 1
fi

# The files are the agent's, so no repository hook runs on them here.
git add -A
git -c core.hooksPath=/dev/null commit --quiet -m "chore(agent): $name" \
  -m "Generated by noon job $NOON_JOB, run $NOON_RUN_ID, from $prompt_file."
printf 'committed %s on %s\n' "$(git rev-parse --short HEAD)" "$branch"

# pre-remove hooks would run files the agent may have edited, on the host. The branch is kept
# because it has an unmerged commit.
cd "$root"
wt remove "$branch" --no-hooks --foreground
