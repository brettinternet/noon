#!/bin/sh
# agent-worktree.sh PROMPT_FILE NAME
# Create a fresh worktree from BASE_REF, run an editing agent there with the prompt on stdin,
# run CHECK_CMD, and commit on success. Never touches your checkout; never pushes unless OPEN_PR=1.
# Successful and no-op runs remove their worktree; failed runs keep it for inspection.
set -eu
prompt_file=$1 name=$2
base=${BASE_REF:-origin/main}
agent=${AGENT_CMD:-codex exec --sandbox workspace-write -}
check=${CHECK_CMD:-make check}

root=$(git rev-parse --show-toplevel)
prompt="$root/$prompt_file"
[ -f "$prompt" ] || { echo "missing prompt file $prompt_file" >&2; exit 1; }
slug="$name-$(date +%Y%m%d-%H%M%S)"
branch="agent/$slug"
tree="$root/.worktrees/$slug"

git fetch --quiet origin
git worktree add --quiet -b "$branch" "$tree" "$base"
printf 'worktree %s on %s\n' "$tree" "$branch"
cd "$tree"

$agent < "$prompt"

if [ -z "$(git status --porcelain)" ]; then
  echo "agent made no changes; removing worktree"
  cd "$root"
  git worktree remove "$tree"
  git branch -D "$branch"
  exit 0
fi

if ! sh -c "$check"; then
  echo "check failed; worktree kept for inspection: $tree" >&2
  exit 1
fi

git add -A
git commit --quiet -m "chore(agent): $name" -m "Generated by noon job $NOON_JOB, run $NOON_RUN_ID, from $prompt_file."
printf 'committed %s on %s\n' "$(git rev-parse --short HEAD)" "$branch"

if [ "${OPEN_PR:-0}" = 1 ]; then
  git push --quiet -u origin "$branch"
  gh pr create --draft --fill --head "$branch"
fi

# The branch holds the result; the worktree is no longer needed.
cd "$root"
git worktree remove "$tree"
